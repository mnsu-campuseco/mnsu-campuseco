const { chromium } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');
const http = require('node:http');
const { spawn } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'docs/assets/phase2-visual');
let server;
async function running() {
  return new Promise(resolve => http.get('http://127.0.0.1:4173', res => {res.resume(); resolve(true);}).on('error',()=>resolve(false)));
}
(async () => {
  await fs.mkdir(out, {recursive:true});
  if (!(await running())) {
    server = spawn(process.execPath, [path.join(__dirname, 'serve.cjs')], {stdio:'ignore', windowsHide:true});
    await new Promise(resolve=>setTimeout(resolve,800));
  }
  const browser = await chromium.launch({channel:'chrome', headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000}, reducedMotion:'reduce'});
  const page = await context.newPage();
  const shot = async (name, locator) => (locator || page).screenshot({path:path.join(out,name+'.png'), animations:'disabled'});
  const section = selector => page.locator('section').filter({has:page.locator(selector)}).first();
  await page.goto('http://127.0.0.1:4173');
  await shot('home');
  await page.goto('http://127.0.0.1:4173/pages/operator.html');
  await page.locator('#tracking').fill('CE-20261004');
  await page.locator('#weight').fill('3.2');
  for(const [id,value] of [['length','12'],['width','8'],['height','6']]) await page.locator('#'+id).fill(value);
  await page.locator('#destination').selectOption({index:1});
  await page.locator('#urgent').check();
  await shot('checkin',section('#checkin-form'));
  await page.locator('#checkin-form button[type=submit]').click();
  await page.locator('#log-search').fill('CE-20261004');
  await shot('new-row',section('#package-log'));
  await page.goto('http://127.0.0.1:4173/pages/courier.html');
  await page.locator('#driver-id').fill('ECO-1234');
  await page.locator('#cart').selectOption('cart-01');
  await page.locator('#shift-form button[type=submit]').click();
  await shot('claim-queue',section('#route-queue'));
  await page.locator('[data-claim="CE-20261004"]').click();
  await shot('milestone',section('#milestone-form'));
  await page.locator('#milestone-form button').click();
  await page.locator('#milestone-form button').click();
  await shot('route-marker',section('#cart-marker'));
  await page.setViewportSize({width:390,height:900});
  await shot('mobile-queue',section('#route-queue'));
  await page.setViewportSize({width:1440,height:1000});
  await shot('desktop-workspace',page.locator('.workspace'));
  await page.locator('#milestone-form button').click();
  await page.goto('http://127.0.0.1:4173/pages/enduser.html');
  await page.locator('#tracking-number').fill('CE-20261004');
  await page.locator('#tracking-form button').click();
  await shot('tracking',section('#tracking-form'));
  await page.locator('#receipt-package').selectOption('CE-20261004');
  await page.locator('#signature').fill('Demo Recipient');
  await page.locator('#receipt-consent').check();
  await page.locator('#signoff-form button').click();
  await shot('receipt',section('#signoff-form'));
  await shot('notifications',section('#notifications'));
  await shot('carbon',section('#carbon-metrics'));
  await shot('registration',section('#registration-form'));
  await shot('preferences-closed',page.locator('#preferences'));
  await page.locator('#preferences-toggle').click();
  await page.locator('#building').selectOption({index:1});
  await page.locator('#delivery-location').fill('Front desk');
  await shot('preferences-open',page.locator('#preferences'));
  await page.reload();
  await page.locator('#tracking-number').fill('CE-20261004');
  await page.locator('#tracking-form button').click();
  await shot('saved-tracking',section('#tracking-form'));
  await browser.close();
  if(server) server.kill();
  console.log('Captured 13 real webpage screenshots in '+out);
})().catch(error=>{console.error(error); if(server)server.kill(); process.exitCode=1;});
